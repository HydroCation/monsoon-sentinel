#!/usr/bin/env python3
"""
Monsoon Sentinel - Embedded C Model Exporter
Converts the trained 40-tree Random Forest classifier from best_model_weights.json
into highly optimized static C source and header files for ARM Cortex-M4.

Generated Files:
  - Core/Inc/model_inference.h
  - Core/Src/model_inference.c
"""

import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
WEIGHTS_PATH = PROJECT_ROOT / "data" / "processed" / "best_model_weights.json"
INC_PATH = PROJECT_ROOT / "Core" / "Inc" / "model_inference.h"
SRC_PATH = PROJECT_ROOT / "Core" / "Src" / "model_inference.c"


def generate_tree_c_function(tree_id: int, tree_dict: dict) -> str:
    """Generates a static C function for a single decision tree with nested if-else statements."""
    def recurse(node_id: int, indent_level: int) -> str:
        indent = "    " * indent_level
        if tree_dict["children_left"][node_id] == -1:
            # Leaf node: determine argmax class
            leaf_values = tree_dict["values"][node_id]
            pred_class = max(range(len(leaf_values)), key=lambda c: leaf_values[c])
            class_enum = f"CLASS_{['BASELINE', 'TILT', 'SHOCK', 'BUFFETING'][pred_class]}"
            return f"{indent}votes[{class_enum}]++;\n"

        feat = tree_dict["feature"][node_id]
        thresh = tree_dict["threshold"][node_id]
        left_child = tree_dict["children_left"][node_id]
        right_child = tree_dict["children_right"][node_id]

        code = f"{indent}if (features[{feat}] <= {thresh:.7f}f) {{\n"
        code += recurse(left_child, indent_level + 1)
        code += f"{indent}}} else {{\n"
        code += recurse(right_child, indent_level + 1)
        code += f"{indent}}}\n"
        return code

    body = recurse(0, 1)
    return f"static void tree_{tree_id}_vote(const float *features, uint16_t *votes)\n{{\n{body}}}\n"


def export_model():
    if not WEIGHTS_PATH.exists():
        raise FileNotFoundError(f"Model weights file not found: {WEIGHTS_PATH}")

    with open(WEIGHTS_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    meta = data["metadata"]
    scaler = data["scaler"]
    trees = data["model_parameters"]["trees"]
    n_trees = len(trees)

    print("=" * 75)
    print("MONSOON SENTINEL EMBEDDED C CODE GENERATOR")
    print("=" * 75)
    print(f"Model Architecture : {meta['model_name']} ({meta.get('option', 'Option A')})")
    print(f"Number of Trees    : {n_trees}")
    print(f"Feature Dimensions : {meta['n_features']}")
    print(f"Physical Regimes   : {meta['n_classes']}")

    # 1. Generate Core/Inc/model_inference.h
    header_content = """/*
 * model_inference.h
 *
 * Auto-generated by scripts/analysis/export_rf_to_c.py
 * Embedded Random Forest inference engine for Monsoon Sentinel (ARM Cortex-M4).
 */

#ifndef MODEL_INFERENCE_H
#define MODEL_INFERENCE_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

#define MODEL_NUM_FEATURES  13
#define MODEL_NUM_CLASSES   4
#define MODEL_NUM_TREES     40

/* Feature Index Enumerations */
typedef enum {
    FEAT_TILT_DEG = 0,
    FEAT_PITCH_DEG,
    FEAT_ROLL_DEG,
    FEAT_VAR_DYN,
    FEAT_RMS_DYN,
    FEAT_P2P_DYN,
    FEAT_CREST_FACTOR,
    FEAT_GYRO_RMS,
    FEAT_DOM_FREQ,
    FEAT_BAND_LOW,
    FEAT_BAND_MID,
    FEAT_BAND_HIGH,
    FEAT_SPECTRAL_RATIO,
    NUM_FEATURES = MODEL_NUM_FEATURES
} feature_id_t;

/* Physical Kinematic Regime Enumerations */
typedef enum {
    CLASS_BASELINE  = 0,
    CLASS_TILT      = 1,
    CLASS_SHOCK     = 2,
    CLASS_BUFFETING = 3,
    NUM_CLASSES     = MODEL_NUM_CLASSES
} regime_class_t;

/**
 * @brief In-place Z-score standard scaling of feature vector: x = (x - mean) / std.
 * @param features Pointer to 13-element float array.
 */
void model_normalize_features(float *features);

/**
 * @brief Evaluates all 40 decision trees and returns class with maximum vote.
 * @param features Pointer to 13-element float array (physical feature vector).
 * @return Winning class index (0: Baseline, 1: Tilt, 2: Shock, 3: Buffeting).
 */
uint8_t model_predict(const float *features);

#ifdef __cplusplus
}
#endif

#endif /* MODEL_INFERENCE_H */
"""

    INC_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(INC_PATH, "w", encoding="utf-8") as f:
        f.write(header_content)
    print(f"[OK] Generated: {INC_PATH}")

    # 2. Generate Core/Src/model_inference.c
    mean_str = ", ".join([f"{m:.7f}f" for m in scaler["mean"]])
    std_str = ", ".join([f"{s:.7f}f" for s in scaler["scale"]])

    c_source_parts = [
        """/*
 * model_inference.c
 *
 * Auto-generated by scripts/analysis/export_rf_to_c.py
 * Embedded Random Forest inference engine for Monsoon Sentinel (ARM Cortex-M4).
 */

#include "model_inference.h"

/* Standard Scaler Parameters (Z-Score Normalization) */
static const float SCALER_MEAN[MODEL_NUM_FEATURES] = {
    """
        + mean_str
        + """
};

static const float SCALER_STD[MODEL_NUM_FEATURES] = {
    """
        + std_str
        + """
};

__attribute__((used))
void model_normalize_features(float *features)
{
    for (uint8_t i = 0; i < MODEL_NUM_FEATURES; i++) {
        features[i] = (features[i] - SCALER_MEAN[i]) / SCALER_STD[i];
    }
}

/* ========================================================================== */
/* Static Decision Tree Implementations (40 Trees, Max Depth 7)               */
/* ========================================================================== */
""",
    ]

    for idx, t in enumerate(trees):
        c_source_parts.append(generate_tree_c_function(idx, t))

    # Add model_predict function with unrolled tree calls
    tree_calls = "\n".join([f"    tree_{i}_vote(features, votes);" for i in range(n_trees)])

    predict_function = f"""
/* ========================================================================== */
/* Model Prediction Entrypoint                                                */
/* ========================================================================== */
__attribute__((used))
uint8_t model_predict(const float *features)
{{
    uint16_t votes[MODEL_NUM_CLASSES] = {{0}};

    /* Execute all 40 decision trees */
{tree_calls}

    /* Class tally argmax */
    uint8_t best_class = CLASS_BASELINE;
    uint16_t max_votes = votes[0];

    for (uint8_t c = 1; c < MODEL_NUM_CLASSES; c++) {{
        if (votes[c] > max_votes) {{
            max_votes = votes[c];
            best_class = c;
        }}
    }}

    return best_class;
}}
"""
    c_source_parts.append(predict_function)

    SRC_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(SRC_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(c_source_parts))
    print(f"[OK] Generated: {SRC_PATH}")
    print("=" * 75)


if __name__ == "__main__":
    export_model()
