def generate_confusion_matrix_table():
    """
    Computes and formats the 4-class row-normalized confusion matrix LaTeX table.
    """
    df = pd.read_csv(CSV_PATH)
    df = df[df["label"] != 2].copy()

    # Temporal session block grouping
    df["group"] = df["source_file"].copy()
    taps_mask = df["source_file"] == "mpu6050_flat_taps_1.csv"
    taps_indices = df[taps_mask].index
    splits = np.array_split(taps_indices, 4)
    for i, block_idx in enumerate(splits, 1):
        df.loc[block_idx, "group"] = f"flat_taps_block_{i}"

    label_remap = {0: 0, 1: 1, 3: 2, 4: 3}
    df["label"] = df["label"].map(label_remap)

    X = df[FEATURE_COLS].values
    y = df["label"].values
    groups = df["group"].values

    sgkf = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)
    rf = RandomForestClassifier(n_estimators=40, max_depth=7, class_weight="balanced", random_state=42)

    oof_preds = np.zeros(len(y), dtype=int)
    for train_idx, val_idx in sgkf.split(X, y, groups):
        rf.fit(X[train_idx], y[train_idx])
        oof_preds[val_idx] = rf.predict(X[val_idx])

    cm = confusion_matrix(y, oof_preds, labels=[0, 1, 2, 3])
    cm_norm = cm.astype("float") / cm.sum(axis=1)[:, np.newaxis] * 100.0

    lines = [
        "% Auto-generated by generate_part2_tables.py",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Normalized Out-of-Fold Confusion Matrix for Deployed Random Forest (5-Fold StratifiedGroupKFold)}",
        "\\label{tab:confusion_matrix}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "& \\multicolumn{4}{c}{\\textbf{Predicted Physical Regime}} & \\\\",
        "\\cmidrule(lr){2-5}",
        "\\textbf{True Regime} & \\textbf{Baseline} & \\textbf{Tilt} & \\textbf{Shock} & \\textbf{Buffeting} & \\textbf{Class Recall} \\\\",
        "\\midrule",
    ]

    for i, name in enumerate(CLASS_NAMES):
        row_str = f"    \\textbf{{{name}}} & "
        cells = []
        for j in range(4):
            count = cm[i, j]
            pct = cm_norm[i, j]
            if i == j:
                cells.append(f"\\textbf{{{pct:.2f}\\%}} ({count:,})")
            elif pct > 0:
                cells.append(f"{pct:.2f}\\% ({count:,})")
            else:
                cells.append("0.00\\% (0)")
        row_str += " & ".join(cells)
        row_str += f" & \\textbf{{{cm_norm[i, i]:.2f}\\%}} \\\\"
        lines.append(row_str)

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")

    with open(CM_TABLE_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[OK] Generated: {CM_TABLE_PATH}")


def main():
    generate_hardware_profile_table()
    generate_confusion_matrix_table()


if __name__ == "__main__":
    main()
