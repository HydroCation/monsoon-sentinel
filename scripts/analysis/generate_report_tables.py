def main():
    if not INPUT_CSV.exists():
        raise FileNotFoundError(f"Feature dataset not found: {INPUT_CSV}")

    df = pd.read_csv(INPUT_CSV)
    print(f"Loaded feature dataset: {INPUT_CSV} ({len(df)} rows)")

