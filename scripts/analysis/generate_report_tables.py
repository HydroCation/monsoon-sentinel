#!/usr/bin/env python3
"""
Automated LaTeX Table Generation for Monsoon Sentinel Technical Reports.
Generates:
  1. Table I  : Dataset Registry & Regime Partitioning -> reports/part1_telemetry/table_dataset_registry.tex
  2. Table II : Physical Feature Extraction Summary     -> reports/part1_telemetry/table_feature_summary.tex
"""

import os
from pathlib import Path
import pandas as pd
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
INPUT_CSV = PROJECT_ROOT / "data" / "processed" / "master_features_v4.csv"
RAW_DIR = PROJECT_ROOT / "data" / "raw"
OUT_DIR = PROJECT_ROOT / "reports" / "part1_telemetry"
OUT_DIR.mkdir(parents=True, exist_ok=True)

TABLE1_PATH = OUT_DIR / "table_dataset_registry.tex"
TABLE2_PATH = OUT_DIR / "table_feature_summary.tex"
TABLE3_PATH = OUT_DIR / "table_timing_budget.tex"

REGIME_ORDER = [
    (0, "Nominal_Baseline"),
    (1, "Structural_Tilt"),
    (2, "Acoustic_Vibration"),
    (3, "Impulse_Shock"),
    (4, "Mast_Buffeting"),
]


def compute_file_duration(fname: str) -> float:
    """Return raw duration in seconds from the raw CSV timestamp delta."""
    fpath = RAW_DIR / fname
    if not fpath.exists():
        return 0.0
    try:
        df_raw = pd.read_csv(fpath)
        if fname == "mpu6050_unstable_ruler_Xaxis_FAN_Ceiling.csv":
            df_raw = df_raw.iloc[1:].reset_index(drop=True)
        if "timestamp_ms" in df_raw.columns and len(df_raw) > 1:
            return float(df_raw["timestamp_ms"].iloc[-1] - df_raw["timestamp_ms"].iloc[0]) / 1000.0
        return float(len(df_raw)) / 100.0
    except Exception:
        return 0.0


def generate_table1(df: pd.DataFrame):
    """
    Table I: Dataset Registry & Regime Partitioning
    Columns: Regime ID, Regime Name, Raw Files Count, Total Windows (N=128), Total Time (s), Class Share (%)
    """
    total_windows_all = len(df)
    
    rows = []
    tot_files = 0
    tot_win = 0
    tot_time = 0.0

    # Map each file to its duration
    unique_files = df["source_file"].unique()
    file_durations = {f: compute_file_duration(f) for f in unique_files}

    for rid, rname in REGIME_ORDER:
        sub = df[df["label"] == rid]
        win_count = len(sub)
        files = sub["source_file"].unique()
        file_count = len(files)
        total_time_s = sum(file_durations.get(f, 0.0) for f in files)
        share_pct = (win_count / total_windows_all) * 100.0

        tot_files += file_count
        tot_win += win_count
        tot_time += total_time_s

        display_name = rname.replace("_", "\\_")
        rows.append(
            f"    {rid} & {display_name} & {file_count} & {win_count:,} & {total_time_s:,.2f} & {share_pct:.2f}\\% \\\\"
        )

    tot_share = 100.00
    rows_str = "\n".join(rows)

    latex_code = (
        "% Auto-generated by generate_report_tables.py\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{Dataset Registry \\& Physical Regime Partitioning (100\\,Hz, $N=128$, $\\text{Step}=64$)}\n"
        "\\label{tab:dataset_registry}\n"
        "\\begin{tabular}{clrcccc}\n"
        "\\toprule\n"
        "\\textbf{ID} & \\textbf{Regime Name} & \\textbf{Raw Files} & \\textbf{Total Windows} & \\textbf{Total Time (s)} & \\textbf{Class Share} \\\\\n"
        "\\midrule\n"
        + rows_str + "\n"
        "\\midrule\n"
        f"    \\textbf{{--}} & \\textbf{{Total / Overall}} & \\textbf{{{tot_files}}} & \\textbf{{{tot_win:,}}} & \\textbf{{{tot_time:,.2f}}} & \\textbf{{{tot_share:.2f}\\%}} \\\\\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table}\n"
    )
    with open(TABLE1_PATH, "w", encoding="utf-8") as f:
        f.write(latex_code)
    print(f"[OK] Generated Table I: {TABLE1_PATH}")
    return latex_code


def generate_table2(df: pd.DataFrame):
    """
    Table II: Physical Feature Extraction Summary
    Calculate mean and standard deviation across all 5 regimes for:
      Static Tilt (deg), Dynamic RMS (g), Peak-to-Peak Accel (g), Crest Factor, Gyro RMS (deg/s), Dominant Frequency (Hz).
    Format values to 4 decimal places where applicable.
    """
    features = [
        ("tilt_deg", "Static Tilt ($^\\circ$)"),
        ("rms_dyn_g", "Dynamic RMS ($g$)"),
        ("p2p_dyn_g", "Peak-to-Peak ($g$)"),
        ("crest_factor", "Crest Factor"),
        ("gyro_rms_dps", "Gyro RMS ($^\\circ/\\text{s}$)"),
        ("dominant_freq_hz", "Dominant Freq (Hz)"),
    ]

    rows = []
    for rid, rname in REGIME_ORDER:
        sub = df[df["label"] == rid]
        display_name = rname.replace("_", "\\_")
        
        stat_entries = []
        for col, _ in features:
            m = sub[col].mean()
            s = sub[col].std()
            stat_entries.append(f"${m:.4f} \\pm {s:.4f}$")
        
        row_line = f"    {display_name} & " + " & ".join(stat_entries) + " \\\\"
        rows.append(row_line)

    rows_str = "\n".join(rows)

    latex_code = (
        "% Auto-generated by generate_report_tables.py\n"
        "\\begin{table*}[htbp]\n"
        "\\centering\n"
        "\\caption{Physical Feature Extraction Summary Across Five Regimes (Mean $\\pm$ Standard Deviation)}\n"
        "\\label{tab:feature_summary}\n"
        "\\begin{tabular}{lcccccc}\n"
        "\\toprule\n"
        "\\textbf{Regime Name} & \\textbf{Static Tilt ($^\\circ$)} & \\textbf{Dynamic RMS ($g$)} & \\textbf{Peak-to-Peak ($g$)} & \\textbf{Crest Factor} & \\textbf{Gyro RMS ($^\\circ/\\text{s}$)} & \\textbf{Dominant Freq (Hz)} \\\\\n"
        "\\midrule\n"
        + rows_str + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table*}\n"
    )
    with open(TABLE2_PATH, "w", encoding="utf-8") as f:
        f.write(latex_code)
    print(f"[OK] Generated Table II: {TABLE2_PATH}")
    return latex_code


